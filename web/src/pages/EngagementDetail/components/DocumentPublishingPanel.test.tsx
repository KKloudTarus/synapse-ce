import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { DocumentPublishingPanel } from './DocumentPublishingPanel'

vi.mock('../../../lib/api', () => ({ api: { me: vi.fn(), listAssessmentCycles: vi.fn() } }))
vi.mock('../../../lib/api/integrations', () => ({ integrationsApi: { listIntegrations: vi.fn() } }))
vi.mock('../../../lib/api/documents', () => ({ documentsApi: { listEngagementDocuments: vi.fn(), listProjectDocuments: vi.fn(), publish: vi.fn(), unpublish: vi.fn(), documentIntent: vi.fn(), resumePreparedPublication: vi.fn() } }))
vi.mock('../../../components/synapse/ConfirmDialog', () => ({ ConfirmDialog: ({ open, onConfirm }: { open: boolean; onConfirm: () => void }) => open ? <button onClick={onConfirm}>Confirm permanent unpublish</button> : null }))

import { api } from '../../../lib/api'
import { integrationsApi } from '../../../lib/api/integrations'
import { documentsApi } from '../../../lib/api/documents'

afterEach(() => { vi.restoreAllMocks(); vi.clearAllMocks(); vi.useRealTimers(); window.sessionStorage.clear() })
function ready(role = 'reviewer', identity: Record<string, unknown> = {}) { vi.mocked(api.me).mockResolvedValue({ role, ...identity } as never); vi.mocked(api.listAssessmentCycles).mockResolvedValue({ items: [], nextCursor: '' } as never); vi.mocked(integrationsApi.listIntegrations).mockResolvedValue([{ id: 'confluence', name: 'Confluence', provider: 'confluence-cloud', enabled: true, archived: false, credentialConfigured: true }] as never); vi.mocked(documentsApi.listEngagementDocuments).mockResolvedValue([]); vi.mocked(documentsApi.listProjectDocuments).mockResolvedValue([]) }

describe('DocumentPublishingPanel', () => {
  it('derives the engagement source and does not expose destination controls', async () => {
    ready(); vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent', state: 'pending' } } as never)
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    await waitFor(() => expect(documentsApi.publish).toHaveBeenCalledWith(expect.objectContaining({ integrationId: 'confluence', sourceKind: 'engagement_report', scopeId: 'eng-1', sourceRef: 'engagement:eng-1' })))
    expect(screen.queryByLabelText(/space/i)).not.toBeInTheDocument()
    expect(screen.queryByLabelText(/group/i)).not.toBeInTheDocument()
  })
  it('hides write controls for non-review roles', async () => { ready('consultant'); render(<DocumentPublishingPanel engagementId="eng-1" />); expect(await screen.findByText(/reviewer or administrator/i)).toBeInTheDocument(); expect(screen.queryByRole('button', { name: 'Publish report' })).not.toBeInTheDocument() })
  it('confirms permanent unpublish before requesting the purge', async () => { ready(); vi.mocked(documentsApi.listEngagementDocuments).mockResolvedValue([{ id: 'link', remoteUrl: 'https://confluence.test/page', remoteVersion: 1, contentHash: 'a'.repeat(64) }] as never); vi.mocked(documentsApi.unpublish).mockResolvedValue({ skipped: false, intent: { id: 'purge', state: 'pending' } } as never); render(<DocumentPublishingPanel engagementId="eng-1" />); fireEvent.click(await screen.findByRole('button', { name: 'Unpublish' })); fireEvent.click(screen.getByRole('button', { name: 'Confirm permanent unpublish' })); await waitFor(() => expect(documentsApi.unpublish).toHaveBeenCalledWith('link', expect.any(String))) })
  it('derives a project summary and only offers completed cycles with a final manifest', async () => {
    ready()
    vi.mocked(api.listAssessmentCycles).mockResolvedValue({ items: [
      { id: 'cycle-final', name: 'Final cycle', projectId: 'project-1', status: 'completed', activeClosureManifestId: 'manifest-1' },
      { id: 'cycle-open', name: 'Open cycle', projectId: 'project-1', status: 'open', activeClosureManifestId: 'manifest-2' },
      { id: 'cycle-other', name: 'Other project', projectId: 'project-2', status: 'completed', activeClosureManifestId: 'manifest-3' },
      { id: 'cycle-no-manifest', name: 'Unreleased', projectId: 'project-1', status: 'completed', activeClosureManifestId: '' },
    ], nextCursor: '' } as never)
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent', state: 'pending' } } as never)
    render(<DocumentPublishingPanel project={{ id: 'project-1', key: 'quality' }} />)
    const source = await screen.findByLabelText('Report source')
    expect(source).toHaveTextContent('Project quality summary')
    expect(source).toHaveTextContent('Closure report · Final cycle')
    expect(source).not.toHaveTextContent('Open cycle')
    expect(source).not.toHaveTextContent('Other project')
    fireEvent.change(source, { target: { value: 'assessment-cycle:cycle-final' } })
    fireEvent.click(screen.getByRole('button', { name: 'Publish report' }))
    await waitFor(() => expect(documentsApi.publish).toHaveBeenCalledWith(expect.objectContaining({ sourceKind: 'assessment_closure_report', scopeId: 'project-1', sourceRef: 'assessment-cycle:cycle-final' })))
  })
  it('lets a reviewer resume only a failed refused create after explaining the sharing check', async () => {
    ready()
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    vi.mocked(documentsApi.resumePreparedPublication).mockResolvedValue({ id: 'intent-1', state: 'pending', action: 'create', version: 5, attempts: 5 } as never)
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    const resume = await screen.findByRole('button', { name: 'Resume prepared publication' })
    expect(screen.getByText(/verifies restricted sharing before any report content is uploaded/i)).toBeInTheDocument()
    fireEvent.click(resume)
    await waitFor(() => expect(documentsApi.resumePreparedPublication).toHaveBeenCalledWith('intent-1', 4))
    await waitFor(() => expect(documentsApi.listEngagementDocuments).toHaveBeenCalledTimes(2))
  })
  it('shows a resume error', async () => {
    ready()
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    vi.mocked(documentsApi.resumePreparedPublication).mockRejectedValue(new Error('Destination sharing could not be verified.'))
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Resume prepared publication' }))
    expect(await screen.findByText('Destination sharing could not be verified.')).toBeInTheDocument()
  })
  it('disables the recovery action while a resume request is pending', async () => {
    ready()
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    let complete: (value: never) => void = () => undefined
    vi.mocked(documentsApi.resumePreparedPublication).mockImplementation(() => new Promise((resolve) => { complete = resolve as never }) as never)
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    const resume = await screen.findByRole('button', { name: 'Resume prepared publication' })
    fireEvent.click(resume)
    await waitFor(() => expect(resume).toBeDisabled())
    complete({ id: 'intent-1', state: 'pending', action: 'create', version: 5, attempts: 5 } as never)
    await waitFor(() => expect(screen.queryByRole('button', { name: 'Resume prepared publication' })).not.toBeInTheDocument())
  })
  it('restarts bounded polling when the same intent resumes and refreshes its published link', async () => {
    vi.useFakeTimers()
    ready()
    vi.mocked(documentsApi.listEngagementDocuments)
      .mockResolvedValueOnce([])
      .mockResolvedValueOnce([])
      .mockResolvedValueOnce([{ id: 'link-1', remoteUrl: 'https://confluence.test/page', remoteVersion: 2, contentHash: 'a'.repeat(64) }] as never)
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    vi.mocked(documentsApi.resumePreparedPublication).mockResolvedValue({ id: 'intent-1', state: 'pending', action: 'create', version: 5, attempts: 5 } as never)
    vi.mocked(documentsApi.documentIntent).mockResolvedValue({ id: 'intent-1', state: 'done', action: 'create', version: 6, attempts: 6 } as never)
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    await act(async () => {})
    fireEvent.click(screen.getByRole('button', { name: 'Publish report' }))
    await act(async () => {})
    fireEvent.click(screen.getByRole('button', { name: 'Resume prepared publication' }))
    await act(async () => {})
    await act(async () => { await vi.advanceTimersByTimeAsync(1500) })
    expect(documentsApi.documentIntent).toHaveBeenCalledWith('intent-1')
    expect(screen.getByText('Published · v2')).toBeInTheDocument()
  })
  it('keeps a long-running intent recoverable with an explicit status refresh after bounded polling ends', async () => {
    vi.useFakeTimers()
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'pending', action: 'create', version: 4, attempts: 1 } } as never)
    vi.mocked(documentsApi.documentIntent)
      .mockResolvedValueOnce({ id: 'intent-1', state: 'pending', action: 'create', version: 4, attempts: 2 } as never)
      .mockResolvedValueOnce({ id: 'intent-1', state: 'pending', action: 'create', version: 4, attempts: 3 } as never)
      .mockResolvedValueOnce({ id: 'intent-1', state: 'pending', action: 'create', version: 4, attempts: 4 } as never)
      .mockResolvedValueOnce({ id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 5, attempts: 5 } as never)
    vi.mocked(documentsApi.resumePreparedPublication).mockResolvedValue({ id: 'intent-1', state: 'pending', action: 'create', version: 6, attempts: 5 } as never)
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    await act(async () => {})
    fireEvent.click(screen.getByRole('button', { name: 'Publish report' }))
    await act(async () => {})
    await act(async () => { await vi.advanceTimersByTimeAsync(4500) })
    expect(documentsApi.documentIntent).toHaveBeenCalledTimes(3)
    fireEvent.click(screen.getByRole('button', { name: 'Refresh status' }))
    await act(async () => {})
    const resume = screen.getByRole('button', { name: 'Resume prepared publication' })
    fireEvent.click(resume)
    expect(documentsApi.resumePreparedPublication).toHaveBeenCalledWith('intent-1', 5)
  })
  it('restores a failed prepared publication on remount without starting another publication', async () => {
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    const first = render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    await screen.findByRole('button', { name: 'Resume prepared publication' })
    first.unmount()

    vi.clearAllMocks()
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.documentIntent).mockResolvedValue({ id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } as never)
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    expect(await screen.findByRole('button', { name: 'Resume prepared publication' })).toBeInTheDocument()
    expect(documentsApi.documentIntent).toHaveBeenCalledWith('intent-1')
    expect(documentsApi.publish).not.toHaveBeenCalled()
  })
  it('does not restore an intent for another user or scope', async () => {
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    const first = render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    await screen.findByRole('button', { name: 'Resume prepared publication' })
    first.unmount()

    vi.clearAllMocks()
    ready('reviewer', { id: 'user-2', tenantId: 'tenant-1' })
    const otherUser = render(<DocumentPublishingPanel engagementId="eng-1" />)
    await screen.findByRole('button', { name: 'Publish report' })
    expect(documentsApi.documentIntent).not.toHaveBeenCalled()
    otherUser.unmount()

    vi.clearAllMocks()
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    render(<DocumentPublishingPanel engagementId="eng-2" />)
    await screen.findByRole('button', { name: 'Publish report' })
    expect(documentsApi.documentIntent).not.toHaveBeenCalled()
  })
  it('keeps the panel usable when session storage is unavailable', async () => {
    vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => { throw new Error('storage disabled') })
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('storage disabled') })
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    expect(await screen.findByRole('button', { name: 'Resume prepared publication' })).toBeInTheDocument()
  })
  it('clears an unavailable saved intent without enabling its recovery action', async () => {
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    vi.mocked(documentsApi.documentIntent).mockRejectedValue(Object.assign(new Error('Not found.'), { status: 404 }))
    const first = render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Refresh status' }))
    await waitFor(() => expect(screen.queryByRole('button', { name: 'Resume prepared publication' })).not.toBeInTheDocument())
    first.unmount()

    vi.clearAllMocks()
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    await screen.findByRole('button', { name: 'Publish report' })
    expect(documentsApi.documentIntent).not.toHaveBeenCalled()
  })
  it('shows an access error and clears a forbidden saved intent', async () => {
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    vi.mocked(documentsApi.documentIntent).mockRejectedValue(Object.assign(new Error('Forbidden.'), { status: 403 }))
    const first = render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Refresh status' }))
    expect(await screen.findByText('You no longer have access to this publication intent.')).toBeInTheDocument()
    first.unmount()

    vi.clearAllMocks()
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    await screen.findByRole('button', { name: 'Publish report' })
    expect(documentsApi.documentIntent).not.toHaveBeenCalled()
  })
  it('does not let a delayed restore overwrite a newer publication in the same scope', async () => {
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'old-intent', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    const first = render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    await screen.findByRole('button', { name: 'Resume prepared publication' })
    first.unmount()

    let resolveRestore: (value: unknown) => void = () => undefined
    vi.clearAllMocks()
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.documentIntent).mockImplementation(() => new Promise((resolve) => { resolveRestore = resolve }) as never)
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'new-intent', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 7, attempts: 5 } } as never)
    vi.mocked(documentsApi.resumePreparedPublication).mockResolvedValue({ id: 'new-intent', state: 'pending', action: 'create', version: 8, attempts: 5 } as never)
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    await waitFor(() => expect(documentsApi.documentIntent).toHaveBeenCalledWith('old-intent'))
    fireEvent.click(screen.getByRole('button', { name: 'Publish report' }))
    await screen.findByRole('button', { name: 'Resume prepared publication' })
    resolveRestore({ id: 'old-intent', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 })
    await act(async () => {})
    fireEvent.click(screen.getByRole('button', { name: 'Resume prepared publication' }))
    expect(documentsApi.resumePreparedPublication).toHaveBeenCalledWith('new-intent', 7)
  })
  it('does not clear a newer publication when a delayed restore is forbidden', async () => {
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'old-intent', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    const first = render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    await screen.findByRole('button', { name: 'Resume prepared publication' })
    first.unmount()

    let rejectRestore: (cause: unknown) => void = () => undefined
    vi.clearAllMocks()
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.documentIntent).mockImplementation(() => new Promise((_, reject) => { rejectRestore = reject }) as never)
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'new-intent', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 7, attempts: 5 } } as never)
    render(<DocumentPublishingPanel engagementId="eng-1" />)
    await waitFor(() => expect(documentsApi.documentIntent).toHaveBeenCalledWith('old-intent'))
    fireEvent.click(screen.getByRole('button', { name: 'Publish report' }))
    await screen.findByRole('button', { name: 'Resume prepared publication' })
    rejectRestore(Object.assign(new Error('Forbidden.'), { status: 403 }))
    await act(async () => {})
    expect(screen.queryByText('You no longer have access to this publication intent.')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Resume prepared publication' })).toBeInTheDocument()
  })
  it('ignores a publication response that arrives after the panel changes scope', async () => {
    let resolvePublish: (value: unknown) => void = () => undefined
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.publish).mockImplementation(() => new Promise((resolve) => { resolvePublish = resolve }) as never)
    const view = render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    expect(screen.getByRole('button', { name: 'Publish report' })).toBeDisabled()
    view.rerender(<DocumentPublishingPanel engagementId="eng-2" />)
    resolvePublish({ skipped: false, intent: { id: 'old-intent', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } })
    await act(async () => {})
    expect(screen.queryByRole('button', { name: 'Resume prepared publication' })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Publish report' })).not.toBeDisabled()
  })
  it('ignores an old scope restoration response after navigation', async () => {
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 } } as never)
    const first = render(<DocumentPublishingPanel engagementId="eng-1" />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    await screen.findByRole('button', { name: 'Resume prepared publication' })
    first.unmount()

    let resolveIntent: (value: unknown) => void = () => undefined
    vi.clearAllMocks()
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1' })
    vi.mocked(documentsApi.documentIntent).mockImplementation(() => new Promise((resolve) => { resolveIntent = resolve }) as never)
    const view = render(<DocumentPublishingPanel engagementId="eng-1" />)
    await waitFor(() => expect(documentsApi.documentIntent).toHaveBeenCalledWith('intent-1'))
    view.rerender(<DocumentPublishingPanel engagementId="eng-2" />)
    resolveIntent({ id: 'intent-1', state: 'failed', action: 'create', errorCode: 'provider_refused', version: 4, attempts: 5 })
    await act(async () => {})
    expect(screen.queryByRole('button', { name: 'Resume prepared publication' })).not.toBeInTheDocument()
  })
  it('skips unavailable assessment-cycle reads while keeping project summary publication available', async () => {
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1', features: { assessmentLifecycleRead: false } })
    vi.mocked(documentsApi.publish).mockResolvedValue({ skipped: false, intent: { id: 'intent-1', state: 'pending', action: 'create', version: 1, attempts: 1 } } as never)
    render(<DocumentPublishingPanel project={{ id: 'project-1', key: 'quality' }} />)
    fireEvent.click(await screen.findByRole('button', { name: 'Publish report' }))
    expect(api.listAssessmentCycles).not.toHaveBeenCalled()
    expect(documentsApi.publish).toHaveBeenCalledWith(expect.objectContaining({ sourceKind: 'project_quality_summary', scopeId: 'project-1' }))
  })
  it('fails closed when enabled assessment-cycle reads are denied', async () => {
    ready('reviewer', { id: 'user-1', tenantId: 'tenant-1', features: { assessmentLifecycleRead: true } })
    vi.mocked(api.listAssessmentCycles).mockRejectedValue(new Error('Cycle access denied.'))
    render(<DocumentPublishingPanel project={{ id: 'project-1', key: 'quality' }} />)
    expect(await screen.findByText('Cycle access denied.')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Publish report' })).not.toBeInTheDocument()
  })
})
