// A nested entry that is not a valid zip is skipped by the EOCD guard, without panicking or emitting.
func TestJarNestedGarbageSkipped(t *testing.T) {
	dir := t.TempDir()
	outer := filepath.Join(dir, "outer.jar")
	writeNestedJar(t, outer, map[string][]byte{
		"BOOT-INF/lib/notazip.jar":          []byte("this is not a zip archive at all"),
		"META-INF/maven/g/a/pom.properties": []byte("groupId=g\nartifactId=a\nversion=1.0.0\n"),
	})
	comps := jarComponents(outer) // must not panic; the valid top-level coordinate still surfaces
	found := false
	for _, c := range comps {
		if c.PURL == "pkg:maven/g/a@1.0.0" {
			found = true
		}
	}
	if !found {
		t.Errorf("a garbage nested jar must be skipped while the valid top-level coordinate is kept, got %+v", comps)
	}
}

// A serialized gemspec with two s.version assignments is not a standard installed spec; fail closed rather
