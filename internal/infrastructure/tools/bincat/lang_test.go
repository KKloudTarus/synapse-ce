// writeJar writes a jar (zip) at path whose entries are the given name->content map.
func writeJar(t *testing.T, path string, entries map[string]string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	f, err := os.Create(path)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	zw := zip.NewWriter(f)
	for name, content := range entries {
		w, err := zw.Create(name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := w.Write([]byte(content)); err != nil {
			t.Fatal(err)
		}
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
}

func TestParsePomProperties(t *testing.T) {
	ok := "#Generated by Maven\ngroupId=com.example\nartifactId=demo\nversion=1.2.3\n"
	g, a, v, got := parsePomProperties([]byte(ok))
	if !got || g != "com.example" || a != "demo" || v != "1.2.3" {
		t.Fatalf("parsePomProperties(valid) = %q %q %q %v", g, a, v, got)
	}
	// Missing version -> rejected (never a coordinate without a concrete version).
	if _, _, _, got := parsePomProperties([]byte("groupId=com.example\nartifactId=demo\n")); got {
		t.Error("a pom.properties with no version must be rejected")
	}
	// PURL-breaking characters in a coordinate -> rejected.
	if _, _, _, got := parsePomProperties([]byte("groupId=com.ex/ample\nartifactId=demo\nversion=1.0\n")); got {
		t.Error("a group with a slash must be rejected")
	}
}

func TestJarComponents(t *testing.T) {
	dir := t.TempDir()
	// A shaded/fat jar embeds one pom.properties per bundled dependency; a single-level scan inventories all.
	jar := filepath.Join(dir, "app.jar")
	writeJar(t, jar, map[string]string{
		"META-INF/maven/org.apache.commons/commons-text/pom.properties": "groupId=org.apache.commons\nartifactId=commons-text\nversion=1.10.0\n",
		"META-INF/maven/com.google.guava/guava/pom.properties":          "groupId=com.google.guava\nartifactId=guava\nversion=31.1-jre\n",
		"META-INF/MANIFEST.MF":  "Manifest-Version: 1.0\n",
		"org/example/App.class": "not-real-bytecode",
	})
	comps := jarComponents(jar)
	sort.Slice(comps, func(i, j int) bool { return comps[i].Name < comps[j].Name })
	want := []sbom.Component{
		{Name: "com.google.guava:guava", Version: "31.1-jre", PURL: "pkg:maven/com.google.guava/guava@31.1-jre", Scope: sbom.ScopeProduction},
		{Name: "org.apache.commons:commons-text", Version: "1.10.0", PURL: "pkg:maven/org.apache.commons/commons-text@1.10.0", Scope: sbom.ScopeProduction},
	}
	if len(comps) != len(want) {
		t.Fatalf("jarComponents returned %d components, want %d: %+v", len(comps), len(want), comps)
	}
	for i := range want {
		if comps[i].Name != want[i].Name || comps[i].Version != want[i].Version || comps[i].PURL != want[i].PURL || comps[i].Scope != want[i].Scope {
			t.Errorf("component %d = %+v, want %+v", i, comps[i], want[i])
		}
	}
	// A jar with no embedded Maven coordinate yields nothing (no guessing from a filename).
	plain := filepath.Join(dir, "plain.jar")
	writeJar(t, plain, map[string]string{"META-INF/MANIFEST.MF": "Manifest-Version: 1.0\n"})
	if got := jarComponents(plain); len(got) != 0 {
		t.Errorf("a jar without pom.properties must yield nothing, got %+v", got)
	}
	// A non-zip file with a .jar name is not a false coordinate.
	bogus := filepath.Join(dir, "bogus.jar")
	if err := os.WriteFile(bogus, []byte("this is not a zip"), 0o644); err != nil {
		t.Fatal(err)
	}
	if got := jarComponents(bogus); got != nil {
		t.Errorf("a non-zip .jar must yield nothing, got %+v", got)
	}
}

func TestNodePackageManifest(t *testing.T) {
	dir := t.TempDir()
	write := func(rel, content string) string {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
		return p
	}

	unscoped := write("app/node_modules/lodash/package.json", `{"name":"lodash","version":"4.17.21"}`)
	scoped := write("app/node_modules/@babel/core/package.json", `{"name":"@babel/core","version":"7.22.0"}`)
	nestedFixture := write("app/node_modules/lodash/test/fixtures/package.json", `{"name":"fixture","version":"9.9.9"}`)
	appRoot := write("app/package.json", `{"name":"my-app","version":"1.0.0"}`)
	noVersion := write("app/node_modules/private-thing/package.json", `{"name":"private-thing"}`)

	if !isNodePackageManifest(unscoped) || !isNodePackageManifest(scoped) {
		t.Error("an installed package manifest must be recognized (scoped and unscoped)")
	}
	if isNodePackageManifest(nestedFixture) {
		t.Error("a nested fixture package.json must NOT be treated as an installed package")
	}
	if isNodePackageManifest(appRoot) {
		t.Error("the project-root package.json (not under node_modules) must NOT be cataloged")
	}

	c, ok := nodeComponent(unscoped)
	if !ok || c.PURL != "pkg:npm/lodash@4.17.21" || c.Name != "lodash" {
		t.Errorf("nodeComponent(unscoped) = %+v, ok=%v", c, ok)
	}
	c, ok = nodeComponent(scoped)
	if !ok || c.PURL != "pkg:npm/%40babel/core@7.22.0" || c.Name != "@babel/core" {
		t.Errorf("nodeComponent(scoped) = %+v, ok=%v", c, ok)
	}
	if _, ok := nodeComponent(noVersion); ok {
		t.Error("a manifest without a version must yield nothing")
	}
}

func TestGemComponent(t *testing.T) {
	dir := t.TempDir()
	write := func(rel, content string) string {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
		return p
	}

	// The serialized form RubyGems writes into specifications/ (Gem::Specification#to_ruby).
	railsSpec := "# -*- encoding: utf-8 -*-\n" +
		"Gem::Specification.new do |s|\n" +
		"  s.name = \"rails\".freeze\n" +
		"  s.version = \"7.0.4\".freeze\n" +
		"  s.platform = \"ruby\".freeze\n" +
		"end\n"
	rails := write("usr/lib/ruby/gems/3.1.0/specifications/rails-7.0.4.gemspec", railsSpec)
	if !isInstalledGemspec(rails) {
		t.Fatal("a *.gemspec under specifications/ must be recognized")
	}
	c, ok := gemComponent(rails)
	if !ok || c.PURL != "pkg:gem/rails@7.0.4" || c.Name != "rails" {
		t.Errorf("gemComponent(rails) = %+v, ok=%v", c, ok)
	}

	// A platform gem keeps the clean version from s.version (the platform lives on its own line).
	nokoSpec := "Gem::Specification.new do |s|\n" +
		"  s.name = \"nokogiri\".freeze\n" +
		"  s.version = \"1.15.0\".freeze\n" +
		"  s.platform = \"x86_64-linux\".freeze\n" +
		"end\n"
	noko := write("usr/lib/ruby/gems/3.1.0/specifications/nokogiri-1.15.0-x86_64-linux.gemspec", nokoSpec)
	if c, ok := gemComponent(noko); !ok || c.PURL != "pkg:gem/nokogiri@1.15.0" {
		t.Errorf("gemComponent(platform gem) = %+v, ok=%v; want clean version", c, ok)
	}

	// The older Gem::Version.new(...) version form is also read.
	oldSpec := "Gem::Specification.new do |s|\n  s.name = \"rake\".freeze\n  s.version = Gem::Version.new(\"13.0.6\")\nend\n"
	old := write("usr/lib/ruby/gems/3.1.0/specifications/rake-13.0.6.gemspec", oldSpec)
	if c, ok := gemComponent(old); !ok || c.PURL != "pkg:gem/rake@13.0.6" {
		t.Errorf("gemComponent(Gem::Version form) = %+v, ok=%v", c, ok)
	}

	// A hand-written source .gemspec (NOT under specifications/) is not treated as an installed spec.
	source := write("app/mygem.gemspec", "Gem::Specification.new do |s|\n  s.name = \"mygem\"\n  s.version = MyGem::VERSION\nend\n")
	if isInstalledGemspec(source) {
		t.Error("a source .gemspec outside specifications/ must NOT be treated as installed")
	}
}

// TestCatalogInstalledLanguages exercises the full rootfs walk over a mixed image: a jar, an installed npm
// package, and an installed gem all surface with matcher-ready PURLs.
func TestCatalogInstalledLanguages(t *testing.T) {
	rootfs := t.TempDir()
	writeJar(t, filepath.Join(rootfs, "opt/app/service.jar"), map[string]string{
		"META-INF/maven/io.netty/netty-common/pom.properties": "groupId=io.netty\nartifactId=netty-common\nversion=4.1.94.Final\n",
	})
	mustWrite := func(rel, content string) {
		p := filepath.Join(rootfs, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	mustWrite("app/node_modules/express/package.json", `{"name":"express","version":"4.18.2"}`)
	mustWrite("usr/lib/ruby/gems/3.1.0/specifications/puma-6.4.0.gemspec",
		"Gem::Specification.new do |s|\n  s.name = \"puma\".freeze\n  s.version = \"6.4.0\".freeze\nend\n")

	comps, err := Cataloger{}.CatalogInstalled(context.Background(), rootfs)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]bool{}
	for _, c := range comps {
		got[c.PURL] = true
	}
	for _, want := range []string{
		"pkg:maven/io.netty/netty-common@4.1.94.Final",
		"pkg:npm/express@4.18.2",
		"pkg:gem/puma@6.4.0",
	} {
		if !got[want] {
			t.Errorf("expected %s in catalog, got %v", want, keys(got))
		}
	}
}

func keys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// jarBytes builds an in-memory jar (zip) from name->content entries.
func jarBytes(t *testing.T, entries map[string]string) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for name, content := range entries {
		w, err := zw.Create(name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := w.Write([]byte(content)); err != nil {
			t.Fatal(err)
		}
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

// writeNestedJar writes an outer jar whose named entries carry raw byte content (e.g. a nested jar).
func writeNestedJar(t *testing.T, path string, raw map[string][]byte) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	f, err := os.Create(path)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	zw := zip.NewWriter(f)
	for name, content := range raw {
		w, err := zw.Create(name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := w.Write(content); err != nil {
			t.Fatal(err)
		}
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
}

func TestJarNestedArchives(t *testing.T) {
	dir := t.TempDir()
	// A Spring Boot fat jar nests its dependency jars under BOOT-INF/lib, each with its own pom.properties.
	nested := jarBytes(t, map[string]string{
		"META-INF/maven/org.apache.logging.log4j/log4j-core/pom.properties": "groupId=org.apache.logging.log4j\nartifactId=log4j-core\nversion=2.14.1\n",
	})
	boot := filepath.Join(dir, "app.jar")
	writeNestedJar(t, boot, map[string][]byte{
		"BOOT-INF/lib/log4j-core-2.14.1.jar": nested,
		"META-INF/MANIFEST.MF":               []byte("Manifest-Version: 1.0\nMain-Class: org.springframework.boot.loader.JarLauncher\n"),
		"BOOT-INF/classes/App.class":         []byte("x"),
	})
	comps := jarComponents(boot)
	found := false
	for _, c := range comps {
		if c.PURL == "pkg:maven/org.apache.logging.log4j/log4j-core@2.14.1" && c.Name == "org.apache.logging.log4j:log4j-core" {
			found = true
		}
	}
	if !found {
		t.Errorf("nested dependency jar must be cataloged, got %+v", comps)
	}
}

func TestNonConcreteVersionRejected(t *testing.T) {
	dir := t.TempDir()
	write := func(rel, content string) string {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
		return p
	}
	// A dist-tag / meta version is not a concrete version; emitting it would key a wrong or unmatched CVE.
	npm := write("app/node_modules/lodash/package.json", `{"name":"lodash","version":"latest"}`)
	if _, ok := nodeComponent(npm); ok {
		t.Error(`npm version "latest" must be rejected`)
	}
	gem := write("usr/lib/ruby/gems/3.1.0/specifications/rack-latest.gemspec",
		"Gem::Specification.new do |s|\n  s.name = \"rack\".freeze\n  s.version = \"latest\".freeze\nend\n")
	if _, ok := gemComponent(gem); ok {
		t.Error(`gem version "latest" must be rejected`)
	}
}

